"""基于固定模板绘制 CSV 图表，不执行模型生成的代码。"""
import csv
import io
import math
import threading
import uuid

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np

from . import db

PLOT_LOCK = threading.Lock()


def read_csv(raw):
    if len(raw) > 2 * 1024 * 1024:
        raise ValueError('CSV 文件请控制在 2 MB 内。')
    try:
        text = raw.decode('utf-8-sig')
    except UnicodeDecodeError:
        try:
            text = raw.decode('gb18030')
        except UnicodeDecodeError as exc:
            raise ValueError('请使用 UTF-8 或 GB18030 编码的 CSV。') from exc
    reader = csv.DictReader(io.StringIO(text))
    headers = reader.fieldnames
    if not headers or len(headers) < 2 or len(set(headers)) != len(headers) or any(not h for h in headers):
        raise ValueError('CSV 至少需要两列，且首行列名必须非空、不能重复。')
    rows = list(reader)
    if not rows or len(rows) > 10000:
        raise ValueError('CSV 需要 1–10000 行数据。')
    if any(None in row or any(v is None for v in row.values()) for row in rows):
        raise ValueError('CSV 每行的列数必须与表头一致。')
    numeric = []
    for name in headers:
        try:
            values = [float(row[name]) for row in rows]
            if all(math.isfinite(x) for x in values):
                numeric.append(name)
        except (ValueError, TypeError):
            pass
    return headers, rows, numeric


def plot(raw, kind='line', x_name='', y_names=None):
    headers, rows, numeric = read_csv(raw)
    if kind not in ('line', 'bar', 'scatter', 'radar', 'radar3d'):
        raise ValueError('未知图型。')
    if len(rows) > 2000:
        raise ValueError('绘图最多支持 2000 行，请先聚合数据，避免不可读的图表。')
    x_name = x_name or headers[0]
    if x_name not in headers:
        raise ValueError('横轴列不存在。')
    y_names = y_names or [name for name in numeric if name != x_name][:4]
    if not y_names or len(y_names) > 8 or any(n not in numeric for n in y_names):
        raise ValueError('请选择 1–8 个不含空值或非数值的指标列。')
    if kind in ('radar', 'radar3d') and (len(y_names) < 3 or len(rows) > 6):
        raise ValueError('雷达图需要至少 3 个数值指标、最多 6 行对象；不同单位请先归一化。')
    if kind == 'scatter' and x_name not in numeric:
        raise ValueError('散点图的横轴也需要是数值列。')
    labels = [str(r[x_name]) for r in rows]
    values = {name: [float(r[name]) for r in rows] for name in y_names}
    chart_id = uuid.uuid4().hex
    script = f'''# Generated by ResearchDock. Reads the adjacent source CSV.
from pathlib import Path
import csv
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

plt.rcParams["font.sans-serif"] = ["Microsoft YaHei", "SimHei", "DejaVu Sans"]
plt.rcParams["axes.unicode_minus"] = False
kind = {kind!r}
x_name = {x_name!r}
y_names = {y_names!r}
labels = {labels!r}
values = {values!r}
fig = plt.figure(figsize=(10, 5.5), dpi=160)
palette = ["#167f73", "#e3a846", "#7188b6", "#be7186", "#8c9d68", "#8a7ca8", "#bd845a", "#719fad"]
if kind in ("radar", "radar3d"):
    ax = fig.add_subplot(111, projection="polar" if kind == "radar" else "3d")
    theta = np.linspace(0, 2*np.pi, len(y_names), endpoint=False)
    theta = np.r_[theta, theta[0]]
    for i, label in enumerate(labels):
        data = np.array([values[n][i] for n in y_names])
        data = np.r_[data, data[0]]
        if kind == "radar":
            ax.plot(theta, data, label=label, color=palette[i % len(palette)])
            ax.fill(theta, data, alpha=.06)
        else:
            ax.plot(data*np.cos(theta), data*np.sin(theta), np.full(len(theta), i), label=label)
    if kind == "radar":
        ax.set_xticks(theta[:-1], y_names)
    else:
        ax.set_zlabel("Object index")
else:
    ax = fig.add_subplot(111)
    x = np.array([float(v) for v in labels]) if kind == "scatter" else np.arange(len(labels))
    for i, name in enumerate(y_names):
        if kind == "bar":
            width = .8/len(y_names)
            ax.bar(x-.4+width/2+i*width, values[name], width=width, label=name, color=palette[i % len(palette)])
        elif kind == "scatter":
            ax.scatter(x, values[name], label=name, s=22, color=palette[i % len(palette)])
        else:
            ax.plot(x, values[name], label=name, linewidth=2, color=palette[i % len(palette)])
    if kind != "scatter":
        ticks = np.unique(np.linspace(0, len(labels)-1, min(12,len(labels))).astype(int))
        ax.set_xticks(ticks, [labels[i] for i in ticks], rotation=25, ha="right")
    ax.set_xlabel(x_name)
    ax.set_ylabel("Value")
    ax.spines[["top", "right"]].set_visible(False)
ax.grid(alpha=.18)
ax.legend(frameon=False, fontsize=9)
fig.tight_layout()
fig.savefig(Path(__file__).with_suffix(".png"), facecolor="white")
fig.savefig(Path(__file__).with_suffix(".svg"), facecolor="white")
plt.close(fig)
'''
    # 只编译执行固定绘图模板和已校验数据，不执行外部生成的代码。
    # 导出的脚本与生成预览图的脚本一致。
    target = db.DATA / 'charts' / chart_id
    with PLOT_LOCK:
        exec(compile(script, str(target.with_suffix('.py')), 'exec'), {'__file__': str(target.with_suffix('.py'))})
    target.with_suffix('.py').write_text(script, encoding='utf-8')
    target.with_suffix('.csv').write_bytes(raw)
    facts = []
    for name in y_names:
        vals = values[name]
        facts.append(f'{name} 范围 {min(vals):g}–{max(vals):g}，首末记录变化 {vals[-1] - vals[0]:+g}')
    caption = f'图：{len(rows)} 条记录的指标比较。' + '；'.join(facts) + '。仅描述样本数值，不推断因果、显著性或未提供的实验条件。'
    return {'id': chart_id, 'image': f'/api/charts/{chart_id}.png', 'svg': f'/api/charts/{chart_id}.svg',
            'script': f'/api/charts/{chart_id}.py', 'csv': f'/api/charts/{chart_id}.csv',
            'caption': caption, 'columns': headers, 'numeric': numeric, 'preview': rows[:12], 'row_count': len(rows)}
